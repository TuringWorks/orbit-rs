    trial_id SERIAL PRIMARY KEY,
    trial_name VARCHAR(200),
    condition VARCHAR(100),
    inclusion_criteria JSONB,
    exclusion_criteria JSONB,
    phase VARCHAR(20),
    status VARCHAR(50)
);

-- Insert sample clinical trial
