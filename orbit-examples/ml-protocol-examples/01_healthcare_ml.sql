-- 6. PREDICTIVE ANALYTICS - READMISSION RISK
-- ----------------------------------------------------------------------------

-- Create hospital admissions table
CREATE TABLE IF NOT EXISTS hospital_admissions (
    admission_id SERIAL PRIMARY KEY,
    patient_id INTEGER REFERENCES patients(patient_id),
    admission_date TIMESTAMP,
    discharge_date TIMESTAMP,
    length_of_stay INTEGER,
    diagnosis VARCHAR(200),
    procedures TEXT[],
    readmission_30day BOOLEAN DEFAULT FALSE
);

-- ML model to predict 30-day readmission risk
CREATE OR REPLACE FUNCTION predict_readmission_risk(
    p_age INTEGER,
    p_length_of_stay INTEGER,
    p_num_procedures INTEGER,
    p_risk_score FLOAT
) RETURNS FLOAT AS $$
DECLARE
    readmission_probability FLOAT;
BEGIN
    -- Simplified logistic regression (in production, use trained ML model)
    readmission_probability := 1.0 / (1.0 + exp(-(
        -2.5 + 
        (p_age * 0.02) + 
        (p_length_of_stay * 0.15) + 
        (p_num_procedures * 0.3) +
        (p_risk_score * 2.0)
    )));
    RETURN readmission_probability;
END;
$$ LANGUAGE plpgsql;

-- Identify high-risk patients for readmission
SELECT 
    p.patient_id,
    p.name,
    p.age,
    ha.length_of_stay,
    array_length(ha.procedures, 1) AS num_procedures,
    p.risk_score,
    predict_readmission_risk(
        p.age, 
        ha.length_of_stay, 
        COALESCE(array_length(ha.procedures, 1), 0),
        p.risk_score
    ) AS readmission_probability
FROM patients p
JOIN hospital_admissions ha ON p.patient_id = ha.patient_id
WHERE ha.discharge_date IS NOT NULL
ORDER BY readmission_probability DESC;

