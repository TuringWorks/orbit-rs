('Jane Smith', 72, 'F', 'O-', 'Diabetes Type 2', '{"heart_rate": 78, "bp_systolic": 130, "bp_diastolic": 85, "temperature": 98.4, "glucose": 180}'),
('Bob Johnson', 58, 'M', 'B+', 'Coronary Artery Disease', '{"heart_rate": 92, "bp_systolic": 150, "bp_diastolic": 95, "temperature": 99.1}');

-- ML-based risk prediction using patient features
-- Note: In production, this would call an ML model via Orbit's ML subsystem
CREATE OR REPLACE FUNCTION predict_patient_risk(
    p_age INTEGER,
    p_heart_rate INTEGER,
    p_bp_systolic INTEGER,
    p_bp_diastolic INTEGER
) RETURNS FLOAT AS $$
DECLARE
    risk_score FLOAT;
BEGIN
    -- Simplified risk calculation (in production, use ML model)
    risk_score := (p_age * 0.3) + 
                  (p_heart_rate * 0.2) + 
                  (p_bp_systolic * 0.3) + 
                  (p_bp_diastolic * 0.2);
    RETURN risk_score / 100.0;
END;
$$ LANGUAGE plpgsql;

-- Update risk scores for all patients
UPDATE patients 
SET risk_score = predict_patient_risk(
    age,
    (vital_signs->>'heart_rate')::INTEGER,
    (vital_signs->>'bp_systolic')::INTEGER,
    (vital_signs->>'bp_diastolic')::INTEGER
);

-- Query high-risk patients
SELECT patient_id, name, age, diagnosis, risk_score
FROM patients
WHERE risk_score > 0.7
ORDER BY risk_score DESC;

