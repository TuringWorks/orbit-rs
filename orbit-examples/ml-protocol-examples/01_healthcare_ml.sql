-- Create patient prescriptions table
CREATE TABLE IF NOT EXISTS prescriptions (
    prescription_id SERIAL PRIMARY KEY,
    patient_id INTEGER REFERENCES patients(patient_id),
    medication_id INTEGER REFERENCES medications(medication_id),
    dosage VARCHAR(50),
    frequency VARCHAR(50),
    start_date DATE,
    end_date DATE
);

-- Check for potential drug interactions using vector similarity
-- Similar chemical structures may indicate interaction risk
SELECT 
    m1.drug_name AS drug1,
    m2.drug_name AS drug2,
    1 - (m1.chemical_structure_embedding <=> m2.chemical_structure_embedding) AS similarity,
    CASE 
        WHEN 1 - (m1.chemical_structure_embedding <=> m2.chemical_structure_embedding) > 0.8 
        THEN 'HIGH INTERACTION RISK'
        WHEN 1 - (m1.chemical_structure_embedding <=> m2.chemical_structure_embedding) > 0.6 
        THEN 'MODERATE RISK'
        ELSE 'LOW RISK'
    END AS risk_level
FROM medications m1
CROSS JOIN medications m2
WHERE m1.medication_id < m2.medication_id
ORDER BY similarity DESC;

