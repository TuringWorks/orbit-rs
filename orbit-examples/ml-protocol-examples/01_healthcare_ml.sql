 '{"slice_thickness": "1mm", "contrast": true}');

-- Create vector index for fast similarity search
CREATE INDEX IF NOT EXISTS medical_images_embedding_idx 
ON medical_images USING ivfflat (image_embedding vector_cosine_ops);

-- Find similar medical images using vector similarity
-- Useful for finding similar cases or anomaly detection
SELECT 
    m1.image_id,
    m1.image_type,
    m1.body_part,
    m1.diagnosis,
    1 - (m1.image_embedding <=> m2.image_embedding) AS similarity_score
FROM medical_images m1
CROSS JOIN medical_images m2
WHERE m1.image_id = 1 AND m2.image_id != 1
ORDER BY m1.image_embedding <=> m2.image_embedding
LIMIT 5;

