('Hypertension Drug Trial', 'Hypertension', 
 '{"age_min": 40, "age_max": 75, "bp_systolic_min": 140}',
 '{"pregnant": true, "kidney_disease": true}',
 'Phase III', 'Recruiting');

-- Match patients to clinical trials using ML-based criteria
SELECT 
    p.patient_id,
    p.name,
    p.age,
    p.diagnosis,
    ct.trial_name,
    ct.phase,
    CASE 
        WHEN p.age >= (ct.inclusion_criteria->>'age_min')::INTEGER 
         AND p.age <= (ct.inclusion_criteria->>'age_max')::INTEGER
         AND (p.vital_signs->>'bp_systolic')::INTEGER >= (ct.inclusion_criteria->>'bp_systolic_min')::INTEGER
        THEN 'ELIGIBLE'
        ELSE 'NOT ELIGIBLE'
    END AS eligibility_status
FROM patients p
CROSS JOIN clinical_trials ct
WHERE ct.status = 'Recruiting'
  AND p.diagnosis ILIKE '%' || ct.condition || '%';

