-- Create time series table for continuous monitoring
CREATE TABLE IF NOT EXISTS vital_signs_timeseries (
    ts_id SERIAL PRIMARY KEY,
    patient_id INTEGER REFERENCES patients(patient_id),
    timestamp BIGINT NOT NULL, -- Unix timestamp in milliseconds
    metric_name VARCHAR(50), -- 'heart_rate', 'blood_pressure', 'oxygen_saturation'
    value FLOAT NOT NULL,
    unit VARCHAR(20)
);

-- Insert time series data for patient monitoring
INSERT INTO vital_signs_timeseries (patient_id, timestamp, metric_name, value, unit) VALUES
(1, extract(epoch from now())::bigint * 1000, 'heart_rate', 85, 'bpm'),
(1, extract(epoch from now())::bigint * 1000 + 60000, 'heart_rate', 87, 'bpm'),
(1, extract(epoch from now())::bigint * 1000 + 120000, 'heart_rate', 84, 'bpm'),
(1, extract(epoch from now())::bigint * 1000, 'oxygen_saturation', 98, '%'),
(1, extract(epoch from now())::bigint * 1000 + 60000, 'oxygen_saturation', 97, '%');

-- Query vital signs with aggregation (moving average)
SELECT 
    patient_id,
    metric_name,
    AVG(value) OVER (
        PARTITION BY patient_id, metric_name 
        ORDER BY timestamp 
        ROWS BETWEEN 2 PRECEDING AND CURRENT ROW
    ) AS moving_avg,
    value AS current_value,
    timestamp
FROM vital_signs_timeseries
WHERE patient_id = 1
ORDER BY timestamp DESC;

-- Detect anomalies in vital signs (values outside normal range)
SELECT 
    patient_id,
    metric_name,
    value,
    timestamp,
    CASE 
        WHEN metric_name = 'heart_rate' AND (value < 60 OR value > 100) THEN 'ALERT'
        WHEN metric_name = 'oxygen_saturation' AND value < 95 THEN 'CRITICAL'
        ELSE 'NORMAL'
    END AS alert_status
FROM vital_signs_timeseries
WHERE patient_id = 1
ORDER BY timestamp DESC;

